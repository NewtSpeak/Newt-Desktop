/** 返回 :shortcode: 形式；未知 emoji 回退 :emoji_hex: */
export function emojiShortcode(emoji: string): string {
  const raw = emoji.trim()
  if (!raw) return ':emoji:'
  const known = EMOJI_SHORTCODES[raw]
  if (known) return `:${known}:`
  // 回退：码点拼接
  const hex = [...raw]
    .map((c) => c.codePointAt(0)!.toString(16))
    .join('_')
  return `:u${hex}:`
}
